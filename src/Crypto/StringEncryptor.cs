    public static string EncryptConfig(string plainText)
    {
        using var aes = Aes.Create();
        aes.Key = AesKey;
        aes.IV = AesIv;
        using var ms = new MemoryStream();
        using (var cs = new CryptoStream(ms, aes.CreateEncryptor(), CryptoStreamMode.Write))
        {
            byte[] input = Encoding.UTF8.GetBytes(plainText);
            cs.Write(input, 0, input.Length);
            cs.FlushFinalBlock();
        }
        return "enc_v1_" + Convert.ToBase64String(ms.ToArray());
    }

    public static string DecryptConfig(string cipherText)
    {
        if (cipherText.StartsWith("enc_v1_", StringComparison.Ordinal))
        {
            cipherText = cipherText["enc_v1_".Length..];
        }

        byte[] cipherBytes = Convert.FromBase64String(cipherText);
        using var aes = Aes.Create();
        aes.Key = AesKey;
        aes.IV = AesIv;
        using var ms = new MemoryStream();
        using (var cs = new CryptoStream(ms, aes.CreateDecryptor(), CryptoStreamMode.Write))
        {
            cs.Write(cipherBytes, 0, cipherBytes.Length);
            cs.FlushFinalBlock();
        }
        return Encoding.UTF8.GetString(ms.ToArray());
    }

    private static readonly byte[] PinSalt =
    [
        0x5A, 0x4F, 0x4C, 0x53, 0x49, 0x5F, 0x50, 0x49,
        0x4E, 0x5F, 0x53, 0x41, 0x4C, 0x54, 0x21, 0x39
