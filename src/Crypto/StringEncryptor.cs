    public static byte[] DeriveKeyFromPin(string pin)
    {
        byte[] pinBytes = Encoding.UTF8.GetBytes(pin);
        byte[] combined = new byte[pinBytes.Length + PinSalt.Length];
        Buffer.BlockCopy(pinBytes, 0, combined, 0, pinBytes.Length);
        Buffer.BlockCopy(PinSalt, 0, combined, pinBytes.Length, PinSalt.Length);
        return SHA256.HashData(combined);
    }

    public static string EncryptWithPin(string plainText, string? pin)
    {
        if (string.IsNullOrEmpty(pin))
        {
            return EncryptConfig(plainText);
        }

        byte[] key = DeriveKeyFromPin(pin);
        using var aes = Aes.Create();
        aes.Key = key;
        aes.GenerateIV();
        using var ms = new MemoryStream();
        ms.Write(aes.IV, 0, aes.IV.Length);
        using (var cs = new CryptoStream(ms, aes.CreateEncryptor(), CryptoStreamMode.Write))
        {
            byte[] input = Encoding.UTF8.GetBytes(plainText);
            cs.Write(input, 0, input.Length);
            cs.FlushFinalBlock();
        }
        return "enc_pin_" + Convert.ToBase64String(ms.ToArray());
    }

    public static string DecryptWithPin(string cipherText, string? pin)
    {
        if (cipherText.StartsWith("enc_v1_", StringComparison.Ordinal))
        {
            return DecryptConfig(cipherText);
        }

        if (!cipherText.StartsWith("enc_pin_", StringComparison.Ordinal) || string.IsNullOrEmpty(pin))
        {
            return DecryptConfig(cipherText);
        }

        try
        {
            cipherText = cipherText["enc_pin_".Length..];
            byte[] raw = Convert.FromBase64String(cipherText);
            if (raw.Length < 16)
            {
                return "";
            }

            byte[] iv = new byte[16];
            Array.Copy(raw, 0, iv, 0, 16);
            byte[] cipherBytes = new byte[raw.Length - 16];
            Array.Copy(raw, 16, cipherBytes, 0, cipherBytes.Length);

            byte[] key = DeriveKeyFromPin(pin);
            using var aes = Aes.Create();
            aes.Key = key;
            aes.IV = iv;
            using var ms = new MemoryStream();
            using (var cs = new CryptoStream(ms, aes.CreateDecryptor(), CryptoStreamMode.Write))
            {
                cs.Write(cipherBytes, 0, cipherBytes.Length);
                cs.FlushFinalBlock();
            }
            return Encoding.UTF8.GetString(ms.ToArray());
        }
        catch
        {
            return "";
        }
    }

    private static string Deobfuscate(byte[] bytes)
    {
        byte[] copy = new byte[bytes.Length];
        for (int i = 0; i < bytes.Length; i++)
        {
            copy[i] = (byte)(bytes[i] ^ (Seed + (i % 23)));
        }
        return Encoding.UTF8.GetString(copy);
    }
